/// RSA-2048 PKCS#1 v1.5 decryption matching `Crypto::RSA2048Decrypt`.
pub fn rsa2048_decrypt(dec_key: &mut [u8; 32], ciphertext: &[u8; 256], is_dk3: bool) -> bool {
    let (modulus_bytes, priv_exp_bytes) = if is_dk3 {
        (
            &PkgDerivedKey3Keyset::MODULUS,
            &PkgDerivedKey3Keyset::PRIVATE_EXPONENT,
        )
    } else {
        (&FakeKeyset::MODULUS, &FakeKeyset::PRIVATE_EXPONENT)
    };

    let c = BigUint::from_bytes_be(ciphertext);
    let n = BigUint::from_bytes_be(modulus_bytes);
    let d = BigUint::from_bytes_be(priv_exp_bytes);

    let m = c.modpow(&d, &n);
    let m_vec = m.to_bytes_be();

    // Pad with leading zeros to 256 bytes
    let mut padded = [0u8; 256];
    if m_vec.len() > 256 {
        return false;
    }
    padded[256 - m_vec.len()..].copy_from_slice(&m_vec);

    // PKCS#1 v1.5 block type 2: 0x00 || 0x02 || PS (non-zero, >= 8 bytes) || 0x00 || M
    if padded[0] == 0x00 && padded[1] == 0x02 {
        if let Some(rel_sep) = padded[2..].iter().position(|&b| b == 0) {
            let sep_idx = 2 + rel_sep;
            if sep_idx >= 10 {
                let msg = &padded[sep_idx + 1..];
                let copy_len = msg.len().min(32);
                dec_key[..copy_len].copy_from_slice(&msg[..copy_len]);
                return true;
            }
        }
    }
    false
}

/// Computes SHA-256 of the 64-byte `(PKGEntry || dk3)` buffer.
pub fn iv_key_hash256(cipher_input: &[u8; 64], ivkey_result: &mut [u8; 32]) {
    let mut hasher = Sha256::new();
    hasher.update(cipher_input);
    let digest = hasher.finalize();
    ivkey_result.copy_from_slice(&digest);
}

/// Decrypts `ciphertext` in-place or into `decrypted` using AES-128-CBC where
/// `iv = ivkey[0..16]` and `key = ivkey[16..32]`.
pub fn aes_cbc_decrypt(ivkey: &[u8; 32], ciphertext: &[u8], decrypted: &mut [u8]) {
    assert_eq!(ciphertext.len(), decrypted.len());
    assert_eq!(ciphertext.len() % 16, 0);

    let iv: &[u8; 16] = ivkey[0..16].try_into().unwrap();
    let key: &[u8; 16] = ivkey[16..32].try_into().unwrap();

    decrypted.copy_from_slice(ciphertext);
    let mut decryptor = Aes128CbcDec::new(key.into(), iv.into());
    for chunk in decrypted.chunks_exact_mut(16) {
        let block = aes::Block::from_mut_slice(chunk);
        decryptor.decrypt_block_mut(block);
    }
}

/// Derives `data_key` and `tweak_key` from `ekpfs` and `seed` using HMAC-SHA256.
pub fn pfs_gen_crypto_key(
    ekpfs: &[u8; 32],
    seed: &[u8; 16],
    data_key: &mut [u8; 16],
    tweak_key: &mut [u8; 16],
) {
    let mut mac = <HmacSha256 as Mac>::new_from_slice(ekpfs).expect("HMAC accepts 32-byte key");
    let mut d = [0u8; 20];
    d[0..4].copy_from_slice(&1u32.to_le_bytes());
    d[4..20].copy_from_slice(seed);
    mac.update(&d);
    let result = mac.finalize().into_bytes();
    tweak_key.copy_from_slice(&result[0..16]);
    data_key.copy_from_slice(&result[16..32]);
}

#[inline]
fn xts_mult(encrypted_tweak: &mut [u8; 16]) {
    let mut feedback = 0u8;
    for byte in encrypted_tweak.iter_mut() {
        let tmp = (*byte >> 7) & 1;
        *byte = (*byte << 1).wrapping_add(feedback);
        feedback = tmp;
    }
    if feedback != 0 {
        encrypted_tweak[0] ^= 0x87;
    }
}

/// Decrypts PFS image sectors (`0x1000` bytes per sector) using AES-128-XTS.
pub fn decrypt_pfs(
    data_key: &[u8; 16],
    tweak_key: &[u8; 16],
    src_image: &[u8],
    dst_image: &mut [u8],
    start_sector: u64,
) {
    let tweak_cipher = Aes128::new(tweak_key.into());
    let data_cipher = Aes128::new(data_key.into());

    for (sec_idx, (src_sec, dst_sec)) in src_image
        .chunks(0x1000)
        .zip(dst_image.chunks_mut(0x1000))
        .enumerate()
    {
        let current_sector = start_sector + sec_idx as u64;
        let mut tweak = [0u8; 16];
        tweak[0..8].copy_from_slice(&current_sector.to_le_bytes());

        let mut encrypted_tweak = aes::Block::from(tweak);
        tweak_cipher.encrypt_block(&mut encrypted_tweak);
        let mut tweak_bytes: [u8; 16] = encrypted_tweak.into();

        for (src_blk, dst_blk) in src_sec.chunks_exact(16).zip(dst_sec.chunks_exact_mut(16)) {
            let mut xor_buf = [0u8; 16];
            for k in 0..16 {
                xor_buf[k] = src_blk[k] ^ tweak_bytes[k];
            }
            let mut block = aes::Block::from(xor_buf);
            data_cipher.decrypt_block(&mut block);
            let dec_bytes: [u8; 16] = block.into();
            for k in 0..16 {
                dst_blk[k] = dec_bytes[k] ^ tweak_bytes[k];
            }
            xts_mult(&mut tweak_bytes);
        }
    }
}
